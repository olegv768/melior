const sizeNote = (employees: number) =>
  employees <= 3
    ? 'Команда маленькая — начните с инструментов, не требующих отдельного администратора.'
    : employees <= 15
      ? 'При такой команде важно закрепить ответственного за каждый процесс.'
      : 'При этом размере команды стоит формализовать регламенты и роли.'

export function buildDemoReport(input: AuditInput): AuditReport {
  const pack = BY_TYPE[input.businessType]
  const focus = FOCUS[input.problem]
  const s = savingsRange(input.turnover)
  const problems = [focus.lead, ...pack.problems.filter((p) => p.title !== focus.lead.title)].slice(0, 4)
  return {
    mode: 'demo',
    summary: `${labelOf.business(input.businessType)}, оборот ${labelOf.turnover(input.turnover)}, ${input.employees} сотр. ${focus.summary} ${sizeNote(input.employees)}`,
    savings: {
      ...s,
      note: 'Ориентир рассчитан как 2–5% оборота и зависит от того, какие меры будут внедрены. Это не обещание результата.',
    },
    problems,
    processes: pack.processes,
    costs: pack.costs,
    automations: pack.automations,
    plan: focus.plan.map((p, i) => ({ week: i + 1, ...p })),
  }
}
